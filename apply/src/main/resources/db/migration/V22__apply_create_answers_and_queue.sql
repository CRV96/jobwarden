-- Auto-apply: the answers to the questions application forms ask, one set per profile, and the jobs the profile asked
-- Claude to apply to, each with how it went. Claude applies in the profile's browser, through the MCP server.
CREATE TABLE application_answers (
    user_id             BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    work_authorization  TEXT,
    needs_sponsorship   BOOLEAN,
    notice_period       TEXT,
    earliest_start      TEXT,
    salary_expectation  TEXT,
    willing_to_relocate BOOLEAN,
    work_preference     TEXT,
    years_of_experience INTEGER CHECK (years_of_experience BETWEEN 0 AND 60),
    cover_letter        VARCHAR(10) NOT NULL DEFAULT 'WRITE' CHECK (cover_letter IN ('NONE', 'WRITE')),
    decline_voluntary   BOOLEAN     NOT NULL DEFAULT TRUE,
    custom              JSONB       NOT NULL DEFAULT '[]',
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- site: the form it was on, e.g. Greenhouse; note: what Claude says happened; question: what a form asked that the
-- answers don't say, when it needs one
CREATE TABLE apply_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    mode           VARCHAR(10) NOT NULL CHECK (mode IN ('REVIEW', 'SUBMIT')),
    status         VARCHAR(20) NOT NULL DEFAULT 'QUEUED'
        CHECK (status IN ('QUEUED', 'APPLYING', 'FILLED', 'APPLIED', 'NEEDS_ANSWER', 'SKIPPED', 'FAILED', 'CANCELLED')),
    site           TEXT,
    note           TEXT,
    question       TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at    TIMESTAMPTZ
);
CREATE INDEX apply_items_user_id_status_idx ON apply_items (user_id, status);
