-- Searches a profile keeps for finding jobs: the Search Builder's filters, under a name. The assistant reads them over
-- MCP, searches, and adds what it finds to found_jobs. Each list is a text array; work and employment types are the
-- constants' names.
CREATE TABLE saved_searches (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name             TEXT        NOT NULL,
    titles           TEXT[]      NOT NULL DEFAULT '{}',
    locations        TEXT[]      NOT NULL DEFAULT '{}',
    skills           TEXT[]      NOT NULL DEFAULT '{}',
    sites            TEXT[]      NOT NULL DEFAULT '{}',
    work_types       TEXT[]      NOT NULL DEFAULT '{}',
    employment_types TEXT[]      NOT NULL DEFAULT '{}',
    excludes         TEXT[]      NOT NULL DEFAULT '{}',
    recency          VARCHAR(10) NOT NULL DEFAULT 'ANY' CHECK (recency IN ('ANY', 'DAY', 'WEEK', 'MONTH', 'YEAR')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Names are unique ignoring case: saving a search under a name it has replaces its filters
CREATE UNIQUE INDEX saved_searches_user_id_name_key ON saved_searches (user_id, lower(name));

-- What the profile asks the assistant to do from the pages: one of the AI Assistant page's presets, with what to look
-- for, or a job's own card (a tailored CV, interview prep, a score, a cover letter, messages, a negotiation brief),
-- which names its job. The assistant, working through the MCP server, reads the waiting requests, does them, adds the
-- jobs it finds to found_jobs, and finishes each with a summary. Each list is a text array; work types are the
-- constants' names.
CREATE TABLE ai_requests (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind           VARCHAR(30) NOT NULL
        CHECK (kind IN ('FIND_JOBS_FOR_CV', 'FIND_JOBS', 'RUN_SAVED_SEARCHES', 'CHECK_POSTINGS', 'FOLLOW_UP', 'TAILOR_CV',
                        'FIND_HIRING_POSTS', 'FIND_RECRUITERS', 'AUTO_APPLY', 'PREPARE_INTERVIEW', 'SCORE_JOB',
                        'SCORE_JOBS', 'SORT_INBOX', 'WRITE_PROJECTS', 'WRITE_COVER_LETTER', 'WRITE_OUTREACH',
                        'NEGOTIATE_OFFER', 'WRITE_STORIES')),
    titles         TEXT[]      NOT NULL DEFAULT '{}',
    locations      TEXT[]      NOT NULL DEFAULT '{}',
    skills         TEXT[]      NOT NULL DEFAULT '{}',
    excludes       TEXT[]      NOT NULL DEFAULT '{}',
    work_types     TEXT[]      NOT NULL DEFAULT '{}',
    seniority      TEXT,
    min_salary     TEXT,
    notes          TEXT,
    recency        VARCHAR(10) NOT NULL DEFAULT 'ANY' CHECK (recency IN ('ANY', 'DAY', 'WEEK', 'MONTH', 'YEAR')),
    use_cv         BOOLEAN     NOT NULL DEFAULT FALSE,
    max_jobs       INTEGER     NOT NULL DEFAULT 15 CHECK (max_jobs BETWEEN 1 AND 50),
    status         VARCHAR(20) NOT NULL DEFAULT 'WAITING'
        CHECK (status IN ('WAITING', 'WORKING', 'DONE', 'FAILED', 'CANCELLED')),
    summary        TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at     TIMESTAMPTZ,
    finished_at    TIMESTAMPTZ,
    application_id BIGINT      REFERENCES applications (id) ON DELETE CASCADE,
    -- A request about one job names it; deleting the job deletes its requests
    CONSTRAINT ai_requests_application_id_check
        CHECK ((kind IN ('TAILOR_CV', 'PREPARE_INTERVIEW', 'SCORE_JOB', 'WRITE_COVER_LETTER', 'WRITE_OUTREACH',
                         'NEGOTIATE_OFFER')) = (application_id IS NOT NULL))
);

CREATE INDEX ai_requests_user_id_status_idx ON ai_requests (user_id, status);
CREATE INDEX ai_requests_application_id_idx ON ai_requests (application_id) WHERE application_id IS NOT NULL;

-- Jobs found for a profile, waiting on the AI Assistant page for a decision: saved or applied to (then they're jobs
-- too), or discarded. A profile has each link once, so a discarded job isn't suggested again. ai_request_id is the
-- request a job was found for, when the assistant found it for one.
CREATE TABLE found_jobs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    saved_search_id BIGINT      REFERENCES saved_searches (id) ON DELETE SET NULL,
    search_label    TEXT,
    title           TEXT        NOT NULL,
    company         TEXT,
    location        TEXT,
    salary          TEXT,
    link            TEXT        NOT NULL,
    source          TEXT,
    description     TEXT,
    note            TEXT,
    posted_on       DATE,
    decision        VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (decision IN ('PENDING', 'SAVED', 'APPLIED', 'DISCARDED')),
    decided_at      TIMESTAMPTZ,
    application_id  BIGINT      REFERENCES applications (id) ON DELETE SET NULL,
    found_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    ai_request_id   BIGINT      REFERENCES ai_requests (id) ON DELETE SET NULL,
    UNIQUE (user_id, link)
);

CREATE INDEX found_jobs_user_id_decision_idx ON found_jobs (user_id, decision);
CREATE INDEX found_jobs_ai_request_id_idx ON found_jobs (ai_request_id) WHERE ai_request_id IS NOT NULL;
