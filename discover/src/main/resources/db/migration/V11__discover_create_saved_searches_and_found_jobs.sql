-- Searches a profile keeps for finding jobs: the Boolean search's filters, under a name. Claude reads them over MCP,
-- searches, and adds what it finds to found_jobs. Each list is a text array; work and employment types are the
-- constants' names.
CREATE TABLE saved_searches (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name             TEXT        NOT NULL,
    titles           TEXT[]      NOT NULL DEFAULT '{}',
    locations        TEXT[]      NOT NULL DEFAULT '{}',
    skills           TEXT[]      NOT NULL DEFAULT '{}',
    sites            TEXT[]      NOT NULL DEFAULT '{}',
    work_types       TEXT[]      NOT NULL DEFAULT '{}',
    employment_types TEXT[]      NOT NULL DEFAULT '{}',
    excludes         TEXT[]      NOT NULL DEFAULT '{}',
    recency          VARCHAR(10) NOT NULL DEFAULT 'ANY' CHECK (recency IN ('ANY', 'DAY', 'WEEK', 'MONTH', 'YEAR')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Names are unique ignoring case: saving a search under a name it has replaces its filters
CREATE UNIQUE INDEX saved_searches_user_id_name_key ON saved_searches (user_id, lower(name));

-- Jobs found for a profile, waiting on the Discover page for a decision: saved or applied to (then they're
-- applications too), or discarded. A profile has each link once, so a discarded job isn't suggested again.
CREATE TABLE found_jobs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    saved_search_id BIGINT      REFERENCES saved_searches (id) ON DELETE SET NULL,
    search_label    TEXT,
    title           TEXT        NOT NULL,
    company         TEXT,
    location        TEXT,
    salary          TEXT,
    link            TEXT        NOT NULL,
    source          TEXT,
    description     TEXT,
    note            TEXT,
    posted_on       DATE,
    decision        VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (decision IN ('PENDING', 'SAVED', 'APPLIED', 'DISCARDED')),
    decided_at      TIMESTAMPTZ,
    application_id  BIGINT      REFERENCES applications (id) ON DELETE SET NULL,
    found_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, link)
);
CREATE INDEX found_jobs_user_id_decision_idx ON found_jobs (user_id, decision);
