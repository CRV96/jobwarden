-- What the profile asks Claude to do from the AI Assistant page: one of the page's presets, with what to look for.
-- Claude, working through the MCP server, reads the waiting requests, does them, adds the jobs it finds to found_jobs,
-- and finishes each with a summary. Each list is a text array; work types are the constants' names.
CREATE TABLE ai_requests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind        VARCHAR(30) NOT NULL
        CHECK (kind IN ('FIND_JOBS_FOR_CV', 'FIND_JOBS', 'RUN_SAVED_SEARCHES', 'CHECK_POSTINGS', 'FOLLOW_UP')),
    titles      TEXT[]      NOT NULL DEFAULT '{}',
    locations   TEXT[]      NOT NULL DEFAULT '{}',
    skills      TEXT[]      NOT NULL DEFAULT '{}',
    excludes    TEXT[]      NOT NULL DEFAULT '{}',
    work_types  TEXT[]      NOT NULL DEFAULT '{}',
    seniority   TEXT,
    min_salary  TEXT,
    notes       TEXT,
    recency     VARCHAR(10) NOT NULL DEFAULT 'ANY' CHECK (recency IN ('ANY', 'DAY', 'WEEK', 'MONTH', 'YEAR')),
    use_cv      BOOLEAN     NOT NULL DEFAULT FALSE,
    max_jobs    INTEGER     NOT NULL DEFAULT 15 CHECK (max_jobs BETWEEN 1 AND 50),
    status      VARCHAR(20) NOT NULL DEFAULT 'WAITING'
        CHECK (status IN ('WAITING', 'WORKING', 'DONE', 'FAILED', 'CANCELLED')),
    summary     TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at  TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);
CREATE INDEX ai_requests_user_id_status_idx ON ai_requests (user_id, status);

-- The request a job was found for, when Claude found it for one
ALTER TABLE found_jobs ADD COLUMN ai_request_id BIGINT REFERENCES ai_requests (id) ON DELETE SET NULL;
CREATE INDEX found_jobs_ai_request_id_idx ON found_jobs (ai_request_id) WHERE ai_request_id IS NOT NULL;
