-- The mailbox JobWarden reads a profile's recruiters' emails from, over IMAP. The password is an app password, kept
-- encrypted with the server's own key (AES-GCM; jobwarden.secret-key, or the key file). The UIDs say how far it has
-- read: a new uid_validity means the server numbered the folder anew, and reading starts over from a few weeks ago.
--
-- How it's read, as connecting it found out: over TLS from the start, or after STARTTLS (starttls), like Proton Mail
-- Bridge. For a server on this computer, which signs its own certificate, the certificate it showed then (its SHA-256
-- fingerprint): the only one trusted after. last_problem says what went wrong the last time, when JobWarden can say it
-- in the profile's language rather than as the server did. read_every_minutes is how often it's read (0: only when the
-- profile asks, with Check now); automation, what becomes of the updates found: ASK leaves them all to the profile,
-- MATCHED applies those matched to a job, CLAUDE also has the assistant sort the others.
CREATE TABLE mail_accounts (
    user_id            BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    host               TEXT        NOT NULL,
    port               INT         NOT NULL,
    username           TEXT        NOT NULL,
    password           TEXT        NOT NULL,
    folder             TEXT        NOT NULL DEFAULT 'INBOX',
    uid_validity       BIGINT,
    last_uid           BIGINT,
    last_checked_at    TIMESTAMPTZ,
    last_error         TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    starttls           BOOLEAN     NOT NULL DEFAULT false,
    certificate        TEXT,
    last_problem       VARCHAR(30) CHECK (last_problem IN ('LOCAL_SERVER_DOWN', 'CERTIFICATE_CHANGED')),
    read_every_minutes INT         NOT NULL DEFAULT 10 CHECK (read_every_minutes BETWEEN 0 AND 10080),
    automation         VARCHAR(10) NOT NULL DEFAULT 'ASK' CHECK (automation IN ('ASK', 'MATCHED', 'CLAUDE'))
);

-- An email that looks like news about one of the profile's jobs: what it says (the status), and the words that said
-- it. It waits until the profile applies it to the job's timeline or dismisses it, or JobWarden or the assistant does
-- (decided_by). One per email, so reading an email again adds nothing. A job deleted since leaves it without one, to
-- pick. text is the start of the email, for the assistant to tell which job it's about.
CREATE TABLE email_updates (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    message_id     TEXT        NOT NULL,
    received_at    TIMESTAMPTZ NOT NULL,
    sender         TEXT,
    subject        TEXT,
    excerpt        TEXT,
    application_id BIGINT      REFERENCES applications (id) ON DELETE SET NULL,
    status         VARCHAR(20) NOT NULL CHECK (status IN ('APPLIED', 'INTERVIEWING', 'OFFER', 'REJECTED')),
    decision       VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (decision IN ('PENDING', 'APPLIED', 'DISMISSED')),
    decided_at     TIMESTAMPTZ,
    text           TEXT,
    decided_by     VARCHAR(10) CHECK (decided_by IN ('YOU', 'JOBWARDEN', 'CLAUDE')),
    UNIQUE (user_id, message_id)
);

CREATE INDEX email_updates_user_id_decision_idx ON email_updates (user_id, decision);
CREATE INDEX email_updates_user_id_decided_at_idx ON email_updates (user_id, decided_at);
