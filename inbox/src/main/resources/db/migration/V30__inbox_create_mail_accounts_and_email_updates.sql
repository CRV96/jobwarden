-- The mailbox JobWarden reads a profile's recruiters' emails from, over IMAP. The password is an app password, kept
-- encrypted with the server's own key (AES-GCM; jobwarden.inbox.secret-key, or the key file). The UIDs say how far it
-- has read: a new uid_validity means the server numbered the folder anew, and reading starts over from a few weeks ago.
CREATE TABLE mail_accounts (
    user_id         BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    host            TEXT        NOT NULL,
    port            INT         NOT NULL,
    username        TEXT        NOT NULL,
    password        TEXT        NOT NULL,
    folder          TEXT        NOT NULL DEFAULT 'INBOX',
    uid_validity    BIGINT,
    last_uid        BIGINT,
    last_checked_at TIMESTAMPTZ,
    last_error      TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- An email that looks like news about one of the profile's jobs: what it says (the status), and the words that said
-- it. It waits until the profile applies it to the job's timeline or dismisses it. One per email, so reading an email
-- again adds nothing. A job deleted since leaves it without one, to pick.
CREATE TABLE email_updates (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    message_id     TEXT        NOT NULL,
    received_at    TIMESTAMPTZ NOT NULL,
    sender         TEXT,
    subject        TEXT,
    excerpt        TEXT,
    application_id BIGINT      REFERENCES applications (id) ON DELETE SET NULL,
    status         VARCHAR(20) NOT NULL CHECK (status IN ('APPLIED', 'INTERVIEWING', 'OFFER', 'REJECTED')),
    decision       VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (decision IN ('PENDING', 'APPLIED', 'DISMISSED')),
    decided_at     TIMESTAMPTZ,
    UNIQUE (user_id, message_id)
);

CREATE INDEX email_updates_user_id_decision_idx ON email_updates (user_id, decision);
