-- Companies a profile watches: their job boards on Greenhouse, Lever or Ashby, which JobWarden reads itself every few
-- hours, with no Claude tokens. The postings that match the profile's saved searches become found jobs, on the AI
-- Assistant page. ats is the board's system; board its name there, as its links have it, in lower case.
CREATE TABLE watched_companies (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name            TEXT        NOT NULL,
    ats             VARCHAR(20) NOT NULL CHECK (ats IN ('GREENHOUSE', 'LEVER', 'LEVER_EU', 'ASHBY')),
    board           TEXT        NOT NULL,
    added_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_checked_at TIMESTAMPTZ,
    last_error      TEXT,
    UNIQUE (user_id, ats, board)
);

-- The found jobs each company's board gave, so the page can say how many are new this week. Stopping watching a
-- company, or the found job going with its profile, takes the rows along.
CREATE TABLE watched_company_finds (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    watched_company_id BIGINT      NOT NULL REFERENCES watched_companies (id) ON DELETE CASCADE,
    found_job_id       BIGINT      NOT NULL REFERENCES found_jobs (id) ON DELETE CASCADE,
    found_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX watched_company_finds_company_found_at_idx ON watched_company_finds (watched_company_id, found_at);
