-- Who's hiring: the people who post that they're hiring, and their posts. Claude finds them on LinkedIn, X and Reddit
-- through the MCP server; the profile adds recruiters by hand too, and follows those whose posts it wants first. A
-- recruiter is one profile link; a post one link. A post saved as a job keeps the job, until the job is deleted.
CREATE TABLE recruiters (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        TEXT        NOT NULL,
    headline    TEXT,
    profile_url TEXT        NOT NULL,
    followed    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, profile_url)
);

CREATE TABLE hiring_posts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    recruiter_id   BIGINT      NOT NULL REFERENCES recruiters (id) ON DELETE CASCADE,
    link           TEXT        NOT NULL,
    text           TEXT        NOT NULL,
    role           TEXT,
    company        TEXT,
    country        VARCHAR(2),
    tags           TEXT[]      NOT NULL DEFAULT '{}',
    posted_on      DATE,
    found_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    hidden         BOOLEAN     NOT NULL DEFAULT FALSE,
    application_id BIGINT REFERENCES applications (id) ON DELETE SET NULL,
    UNIQUE (user_id, link)
);
CREATE INDEX hiring_posts_recruiter_id_idx ON hiring_posts (recruiter_id);
