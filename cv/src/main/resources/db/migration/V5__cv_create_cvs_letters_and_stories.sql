-- A profile's CV, one of each kind per profile: a file uploaded as it is, with the text read out of it so the assistant
-- can match jobs against it; and the fields the CV page builds one from. Each list of the fields (experience, education,
-- languages, certifications, projects) is a JSON array of objects, in the order the page shows them.
CREATE TABLE cv_files (
    user_id      BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    file_name    TEXT        NOT NULL,
    content_type TEXT        NOT NULL,
    content      BYTEA       NOT NULL,
    size_bytes   BIGINT      NOT NULL,
    text         TEXT,
    uploaded_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cv_details (
    user_id        BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    full_name      TEXT,
    headline       TEXT,
    email          TEXT,
    phone          TEXT,
    location       TEXT,
    website        TEXT,
    linkedin       TEXT,
    github         TEXT,
    summary        TEXT,
    skills         TEXT[]      NOT NULL DEFAULT '{}',
    experience     JSONB       NOT NULL DEFAULT '[]',
    education      JSONB       NOT NULL DEFAULT '[]',
    languages      JSONB       NOT NULL DEFAULT '[]',
    certifications JSONB       NOT NULL DEFAULT '[]',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    projects       JSONB       NOT NULL DEFAULT '[]'
);

-- A profile's CV rewritten by the assistant for one job: the same fields as cv_details, as one JSON document, with the
-- posting's keywords it covers and those it can't honestly claim. One per job; deleting the job deletes it.
CREATE TABLE tailored_cvs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id   BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    details          JSONB       NOT NULL,
    matched_keywords TEXT[]      NOT NULL DEFAULT '{}',
    missing_keywords TEXT[]      NOT NULL DEFAULT '{}',
    notes            TEXT,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);

CREATE INDEX tailored_cvs_application_id_idx ON tailored_cvs (application_id);

-- The profile's GitHub account: its user name, a token (encrypted) when it gave one for private repositories, and the
-- repositories it chose for the assistant to write the CV's projects from, as owner/name.
CREATE TABLE github_accounts (
    user_id      BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    username     TEXT        NOT NULL,
    token        TEXT,
    repositories TEXT[]      NOT NULL DEFAULT '{}',
    connected_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A cover letter for one of the profile's jobs, written by the assistant from the CV and the posting, and changed by the
-- profile as it likes: the letter from the greeting to the sign-off, without the name, which the CV page has. One per
-- job; deleting the job deletes it.
CREATE TABLE cover_letters (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    body           TEXT        NOT NULL,
    notes          TEXT,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);

CREATE INDEX cover_letters_application_id_idx ON cover_letters (application_id);

-- The profile's base letter: a cover letter of its own, written once, that each job's letter starts from, by hand or by
-- the assistant, which keeps its voice and the paragraphs it always uses. {company} and {role} in it stand for the
-- job's company and title. One per profile.
CREATE TABLE base_letters (
    user_id    BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    body       TEXT        NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Messages to someone about one of the profile's jobs, for the profile to send itself: a LinkedIn connection note,
-- which LinkedIn caps at 300 characters, and an email. JobWarden never sends them. One per person per job; deleting
-- the job deletes them.
CREATE TABLE outreach_drafts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id  BIGINT       NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    recipient_name  TEXT         NOT NULL,
    recipient_role  TEXT,
    recipient_link  TEXT,
    recipient_email TEXT,
    linkedin_note   VARCHAR(300),
    email_subject   TEXT,
    email_body      TEXT,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX outreach_drafts_application_id_idx ON outreach_drafts (application_id);
CREATE INDEX outreach_drafts_user_id_application_id_idx ON outreach_drafts (user_id, application_id);

-- The profile's story bank: what it did, told the STAR way (the situation, the task, what it did, the result), to tell
-- in interviews again and again. Kept with the CV; the interview briefs draw on them.
CREATE TABLE cv_stories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title      TEXT        NOT NULL,
    situation  TEXT,
    task       TEXT,
    action     TEXT,
    result     TEXT,
    skills     TEXT[]      NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX cv_stories_user_id_idx ON cv_stories (user_id);
