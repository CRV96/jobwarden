-- A profile's CV rewritten by Claude for one job: the same fields as cv_details, as one JSON document, with the
-- posting's keywords it covers and those it can't honestly claim. One per job; deleting the job deletes it.
CREATE TABLE tailored_cvs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id   BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    details          JSONB       NOT NULL,
    matched_keywords TEXT[]      NOT NULL DEFAULT '{}',
    missing_keywords TEXT[]      NOT NULL DEFAULT '{}',
    notes            TEXT,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);
CREATE INDEX tailored_cvs_application_id_idx ON tailored_cvs (application_id);
