-- A cover letter for one of the profile's jobs, written by Claude from the CV and the posting, and changed by the
-- profile as it likes: the letter from the greeting to the sign-off, without the name, which the CV page has. One per
-- job; deleting the job deletes it.
CREATE TABLE cover_letters (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    body           TEXT        NOT NULL,
    notes          TEXT,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);
CREATE INDEX cover_letters_application_id_idx ON cover_letters (application_id);

-- Messages to someone about one of the profile's jobs, for the profile to send itself: a LinkedIn connection note,
-- which LinkedIn caps at 300 characters, and an email. JobWarden never sends them. One per person per job; deleting
-- the job deletes them.
CREATE TABLE outreach_drafts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id  BIGINT       NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    recipient_name  TEXT         NOT NULL,
    recipient_role  TEXT,
    recipient_link  TEXT,
    recipient_email TEXT,
    linkedin_note   VARCHAR(300),
    email_subject   TEXT,
    email_body      TEXT,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX outreach_drafts_application_id_idx ON outreach_drafts (application_id);
CREATE INDEX outreach_drafts_user_id_application_id_idx ON outreach_drafts (user_id, application_id);

-- The profile's story bank: what it did, told the STAR way (the situation, the task, what it did, the result), to tell
-- in interviews again and again. Kept with the CV; the interview briefs draw on them.
CREATE TABLE cv_stories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title      TEXT        NOT NULL,
    situation  TEXT,
    task       TEXT,
    action     TEXT,
    result     TEXT,
    skills     TEXT[]      NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX cv_stories_user_id_idx ON cv_stories (user_id);
