-- The terms of an offer a job made the profile, as typed in on the job's page, to compare offers side by side. The
-- base salary is text, like a posting's, so the salaries page's reading compares it; the rest is shown as typed. One
-- per job; deleting the job deletes it.
CREATE TABLE job_offers (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    base_salary    TEXT,
    bonus          TEXT,
    equity         TEXT,
    signing_bonus  TEXT,
    time_off       TEXT,
    benefits       TEXT,
    start_date     DATE,
    respond_by     DATE,
    notes          TEXT,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);
CREATE INDEX job_offers_application_id_idx ON job_offers (application_id);

-- What Claude wrote to negotiate an offer: where it stands against the market and the other offers, what to ask for
-- and the least to accept, the leverage, what else to ask for, what to say, an email to send, what to watch out for,
-- and where the figures come from. One per job; deleting the job deletes it.
CREATE TABLE negotiation_briefs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    position       TEXT        NOT NULL,
    target         TEXT,
    walk_away      TEXT,
    leverage       TEXT[]      NOT NULL DEFAULT '{}',
    asks           TEXT[]      NOT NULL DEFAULT '{}',
    script         TEXT,
    email          TEXT,
    watch_out      TEXT,
    sources        TEXT[]      NOT NULL DEFAULT '{}',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);
CREATE INDEX negotiation_briefs_application_id_idx ON negotiation_briefs (application_id);

