-- A profile's jobs ("applications"), each with its story on a timeline (application_events), and what's kept beside
-- them: the sites' icons and the companies' logos, the reminders and the calendar feed, and what the assistant wrote
-- for a job (its fit, an interview brief, a negotiation brief) with the offer it made. Everything of a job goes with
-- it, and everything of a profile with the profile.

-- A job: bookmarked or applied to, and how it's going. The link is the posting's, when there's one (a referral or a
-- recruiter's email has none); raw_payload the schema.org JobPosting it was saved from. notes is free text about the
-- job as a whole; what happened when goes on the timeline. The contact, who referred the profile, when applications to
-- the posting close (deadline) and when to follow up next are the job's facts besides the timeline. applied_by is who
-- sent the application: the profile, the assistant from the Auto-apply page, or the browser extension; unknown (NULL)
-- for those never applied to, or applied to before it was kept. archived_at is when the profile archived the job:
-- archived jobs leave the list, the pipeline, the calendar and its feed, and the offers, and stay in the statistics and
-- the salaries.
CREATE TABLE applications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title           TEXT        NOT NULL,
    company         TEXT,
    description     TEXT,
    link            TEXT,
    location        TEXT,
    salary          TEXT,
    employment_type TEXT,
    source          TEXT,
    raw_payload     JSONB,
    current_status  VARCHAR(20) NOT NULL
        CHECK (current_status IN ('SAVED', 'APPLIED', 'INTERVIEWING', 'OFFER', 'POSITION_REOPENED', 'REJECTED',
                                  'NO_RESPONSE', 'POSITION_CLOSED', 'WITHDRAWN')),
    captured_at     TIMESTAMPTZ NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    notes           TEXT,
    contact_name    TEXT,
    contact_role    TEXT,
    contact_email   TEXT,
    contact_phone   TEXT,
    contact_link    TEXT,
    referred_by     TEXT,
    deadline        DATE,
    follow_up_on    DATE,
    applied_by      VARCHAR(10) CHECK (applied_by IN ('YOU', 'CLAUDE', 'EXTENSION')),
    archived_at     TIMESTAMPTZ
);

CREATE INDEX applications_user_id_current_status_idx ON applications (user_id, current_status);
CREATE INDEX applications_user_id_follow_up_on_idx ON applications (user_id, follow_up_on) WHERE follow_up_on IS NOT NULL;
CREATE INDEX applications_user_id_archived_idx ON applications (user_id) WHERE archived_at IS NOT NULL;

-- A step of a job's timeline. It has a date, and a time of day only when it's known: both wall-clock values, read in
-- the time zone the app runs in. An interview says how it takes place, where and how long; its stage label is the
-- round. A rejection may say why; AUTOMATED_EMAIL is the automatic email that gives no reason.
CREATE TABLE application_events (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id     BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    stage_category     VARCHAR(20) NOT NULL
        CHECK (stage_category IN ('SAVED', 'APPLIED', 'INTERVIEWING', 'OFFER', 'POSITION_REOPENED', 'REJECTED',
                                  'NO_RESPONSE', 'POSITION_CLOSED', 'WITHDRAWN')),
    stage_label        TEXT,
    note               TEXT,
    rejection_reason   VARCHAR(30)
        CHECK (rejection_reason IN ('SALARY_MISMATCH', 'POSITION_FILLED', 'LACK_OF_EXPERIENCE', 'NO_RESPONSE',
                                    'AUTOMATED_EMAIL', 'OTHER')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    event_date         DATE        NOT NULL,
    event_time         TIME,
    interview_format   VARCHAR(20) CHECK (interview_format IN ('PHONE', 'VIDEO', 'ON_SITE', 'TAKE_HOME')),
    interview_location TEXT,
    duration_minutes   INTEGER     CHECK (duration_minutes > 0),
    CONSTRAINT rejection_reason_only_when_rejected
        CHECK (rejection_reason IS NULL OR stage_category = 'REJECTED'),
    CONSTRAINT interview_details_only_when_interviewing
        CHECK ((interview_format IS NULL AND interview_location IS NULL AND duration_minutes IS NULL)
            OR stage_category = 'INTERVIEWING')
);

CREATE INDEX application_events_application_id_idx ON application_events (application_id);

-- The icon of each site a profile saved postings from (the source of its jobs), as the browser showed it on the
-- posting's tab: a small PNG, which the lists show next to the site. One per profile and site; saving another posting
-- from the site replaces it.
CREATE TABLE source_icons (
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    source     TEXT        NOT NULL,
    image      BYTEA       NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, source)
);

-- The company's logo for a job, from its posting, made into a small PNG: the pages show it before the job's title.
CREATE TABLE company_logos (
    application_id BIGINT      PRIMARY KEY REFERENCES applications (id) ON DELETE CASCADE,
    image          BYTEA       NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Reminders set on what the calendar shows: an event of a job's timeline (e.g. an interview), the day its applications
-- close, or the day to follow up on it. Each comes some time before its entry (remind_before), once for each time the
-- entry has: notified_for is the start it last came for, so an interview moved to another day reminds again. They go
-- with their job, and with their event.
CREATE TABLE reminders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    kind           VARCHAR(20) NOT NULL CHECK (kind IN ('EVENT', 'DEADLINE', 'FOLLOW_UP')),
    event_id       BIGINT      REFERENCES application_events (id) ON DELETE CASCADE,
    remind_before  VARCHAR(20) NOT NULL CHECK (remind_before IN ('AT_TIME', 'MINUTES_15', 'HOUR_1', 'DAY_1', 'WEEK_1')),
    notified_for   TIMESTAMP,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT reminders_event_only_on_events CHECK ((kind = 'EVENT') = (event_id IS NOT NULL)),
    CONSTRAINT reminders_once_per_entry UNIQUE NULLS NOT DISTINCT (application_id, kind, event_id, remind_before)
);

CREATE INDEX reminders_user_id_idx ON reminders (user_id);

-- The secret address calendar apps subscribe to a profile's calendar at: whoever has it reads the calendar, so it's
-- long and random, and the calendar page makes a new one when asked, which stops the old one.
CREATE TABLE calendar_feeds (
    user_id    BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    token      VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- What the assistant found out to prepare the profile for a job's interview: the company, the role, the questions
-- likely asked, the profile's own stories to tell, questions to ask them, what to watch out for, and where it read it
-- all. story_ids are the stories of the story bank (cv_stories, in the cv module) it draws on, the best first: plain
-- ids, without a foreign key across the modules, so a story deleted since is left out when the brief is shown. One per
-- job.
CREATE TABLE interview_briefs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    company        TEXT        NOT NULL,
    role           TEXT,
    questions      TEXT[]      NOT NULL DEFAULT '{}',
    stories        TEXT[]      NOT NULL DEFAULT '{}',
    ask_them       TEXT[]      NOT NULL DEFAULT '{}',
    watch_out      TEXT,
    sources        TEXT[]      NOT NULL DEFAULT '{}',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    story_ids      BIGINT[]    NOT NULL DEFAULT '{}',
    UNIQUE (user_id, application_id)
);

CREATE INDEX interview_briefs_application_id_idx ON interview_briefs (application_id);

-- How well the profile fits a job: the posting's requirements as the assistant read them, each a must-have or a plus,
-- met, partly met or missing by the CV; and the score JobWarden works out from them, from 1 to 5, the same way for
-- every job. One per job.
CREATE TABLE job_fits (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT        NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    score          NUMERIC(2, 1) NOT NULL CHECK (score BETWEEN 1 AND 5),
    summary        TEXT,
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);

CREATE INDEX job_fits_application_id_idx ON job_fits (application_id);

CREATE TABLE job_fit_requirements (
    job_fit_id BIGINT      NOT NULL REFERENCES job_fits (id) ON DELETE CASCADE,
    position   INT         NOT NULL,
    text       TEXT        NOT NULL,
    importance VARCHAR(10) NOT NULL CHECK (importance IN ('MUST', 'NICE')),
    meets      VARCHAR(10) NOT NULL CHECK (meets IN ('MET', 'PARTIAL', 'MISSING')),
    note       TEXT,
    PRIMARY KEY (job_fit_id, position)
);

-- The terms of an offer a job made the profile, as typed in on the job's page, to compare offers side by side. The base
-- salary is a figure (an amount, its currency and what it pays for); base_salary is the words, read until a figure is
-- saved, and the posting's when there's neither. The rest is shown as typed. One per job.
CREATE TABLE job_offers (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id       BIGINT         NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    base_salary          TEXT,
    time_off             TEXT,
    benefits             TEXT,
    start_date           DATE,
    respond_by           DATE,
    notes                TEXT,
    updated_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    base_salary_amount   NUMERIC(14, 2) CHECK (base_salary_amount > 0),
    base_salary_currency VARCHAR(3),
    base_salary_period   VARCHAR(5)     CHECK (base_salary_period IN ('HOUR', 'DAY', 'WEEK', 'MONTH', 'YEAR')),
    UNIQUE (user_id, application_id)
);

CREATE INDEX job_offers_application_id_idx ON job_offers (application_id);

-- What an offer pays on top of its base salary, each with how often, so a year of it all can be counted: a bonus, meal
-- vouchers, shares, a signing bonus, or other money, from the company or from elsewhere. An amount is in a currency,
-- or a percentage of the base salary (%); without one, the note says what it is. In the order typed in.
CREATE TABLE job_offer_extras (
    offer_id  BIGINT         NOT NULL REFERENCES job_offers (id) ON DELETE CASCADE,
    position  INTEGER        NOT NULL CHECK (position >= 0),
    kind      VARCHAR(13)    NOT NULL CHECK (kind IN ('BONUS', 'MEAL_VOUCHERS', 'EQUITY', 'SIGNING_BONUS', 'OTHER')),
    amount    NUMERIC(14, 2) CHECK (amount > 0),
    unit      VARCHAR(3)     CHECK (unit ~ '^([A-Z]{3}|%)$'),
    frequency VARCHAR(11)    NOT NULL CHECK (frequency IN ('WORKING_DAY', 'MONTH', 'QUARTER', 'YEAR', 'ONCE', 'EVENT')),
    note      VARCHAR(200),
    PRIMARY KEY (offer_id, position),
    CHECK ((amount IS NULL) = (unit IS NULL)),
    CHECK (amount IS NOT NULL OR note IS NOT NULL)
);

-- What the assistant wrote to negotiate an offer: where it stands against the market and the other offers, what to ask
-- for and the least to accept, the leverage, what else to ask for, what to say, an email to send, what to watch out
-- for, and where the figures come from. One per job.
CREATE TABLE negotiation_briefs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    position       TEXT        NOT NULL,
    target         TEXT,
    walk_away      TEXT,
    leverage       TEXT[]      NOT NULL DEFAULT '{}',
    asks           TEXT[]      NOT NULL DEFAULT '{}',
    script         TEXT,
    email          TEXT,
    watch_out      TEXT,
    sources        TEXT[]      NOT NULL DEFAULT '{}',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);

CREATE INDEX negotiation_briefs_application_id_idx ON negotiation_briefs (application_id);
