-- Reminders set on what the calendar shows: an event of a job's timeline (e.g. an interview), the day its applications
-- close, or the day to follow up on it. Each comes some time before its entry (remind_before), once for each time the
-- entry has: notified_for is the start it last came for, so an interview moved to another day reminds again. They go
-- with their job, and with their event.
CREATE TABLE reminders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    kind           VARCHAR(20) NOT NULL CHECK (kind IN ('EVENT', 'DEADLINE', 'FOLLOW_UP')),
    event_id       BIGINT      REFERENCES application_events (id) ON DELETE CASCADE,
    remind_before  VARCHAR(20) NOT NULL CHECK (remind_before IN ('AT_TIME', 'MINUTES_15', 'HOUR_1', 'DAY_1', 'WEEK_1')),
    notified_for   TIMESTAMP,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT reminders_event_only_on_events CHECK ((kind = 'EVENT') = (event_id IS NOT NULL)),
    CONSTRAINT reminders_once_per_entry UNIQUE NULLS NOT DISTINCT (application_id, kind, event_id, remind_before)
);

CREATE INDEX reminders_user_id_idx ON reminders (user_id);
