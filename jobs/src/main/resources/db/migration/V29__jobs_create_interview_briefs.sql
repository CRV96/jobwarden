-- What Claude found out to prepare the profile for a job's interview: the company, the role, the questions likely
-- asked, the profile's own stories to tell, questions to ask them, what to watch out for, and where it read it all.
-- One per job; deleting the job deletes it.
CREATE TABLE interview_briefs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    company        TEXT        NOT NULL,
    role           TEXT,
    questions      TEXT[]      NOT NULL DEFAULT '{}',
    stories        TEXT[]      NOT NULL DEFAULT '{}',
    ask_them       TEXT[]      NOT NULL DEFAULT '{}',
    watch_out      TEXT,
    sources        TEXT[]      NOT NULL DEFAULT '{}',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);

CREATE INDEX interview_briefs_application_id_idx ON interview_briefs (application_id);
