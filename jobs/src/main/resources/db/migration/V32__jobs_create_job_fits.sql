-- How well the profile fits a job: the posting's requirements as Claude read them, each a must-have or a plus, met,
-- partly met or missing by the CV; and the score JobWarden works out from them, from 1 to 5, the same way for every
-- job. One per job; deleting the job deletes it.
CREATE TABLE job_fits (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT       NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    score          NUMERIC(2, 1) NOT NULL CHECK (score BETWEEN 1 AND 5),
    summary        TEXT,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);

CREATE INDEX job_fits_application_id_idx ON job_fits (application_id);

CREATE TABLE job_fit_requirements (
    job_fit_id BIGINT      NOT NULL REFERENCES job_fits (id) ON DELETE CASCADE,
    position   INT         NOT NULL,
    text       TEXT        NOT NULL,
    importance VARCHAR(10) NOT NULL CHECK (importance IN ('MUST', 'NICE')),
    meets      VARCHAR(10) NOT NULL CHECK (meets IN ('MET', 'PARTIAL', 'MISSING')),
    note       TEXT,
    PRIMARY KEY (job_fit_id, position)
);
