-- What the assistant found out on the web about a job's company, for the job's page: who they are, the employer's
-- ratings, what the people who work there praise and complain about, what it pays, its benefits, its news, how its
-- interviews go, what to watch out for, and where it read it all. One per job; it goes with the job, and with the
-- profile.
CREATE TABLE company_research (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    application_id BIGINT      NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
    company        TEXT        NOT NULL,
    ratings        TEXT[]      NOT NULL DEFAULT '{}',
    pros           TEXT[]      NOT NULL DEFAULT '{}',
    cons           TEXT[]      NOT NULL DEFAULT '{}',
    salaries       TEXT[]      NOT NULL DEFAULT '{}',
    benefits       TEXT[]      NOT NULL DEFAULT '{}',
    news           TEXT[]      NOT NULL DEFAULT '{}',
    interviews     TEXT,
    watch_out      TEXT,
    sources        TEXT[]      NOT NULL DEFAULT '{}',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, application_id)
);

CREATE INDEX company_research_application_id_idx ON company_research (application_id);
