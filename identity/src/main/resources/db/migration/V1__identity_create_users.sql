-- The profiles: each keeps its own job hunt. Their names are unique ignoring case (users_name_lower_key), the rule
-- UserService checks, so two requests arriving together can't create both "Robert" and "robert".
--
-- public_id is the id a profile shows, to copy into the browser extension and an assistant's settings: a UUID made
-- when it's created, which tells nothing of how many profiles there are; id stays the number the database counts with.
-- image_changed_at says a profile has a photo, and when it last changed, which the pages put in its address so the
-- browser keeps it until it changes. assistant is the AI assistant it works with: its pages write their prompts and
-- terminal commands for that one. password_hash is its own password's hash, if it has one, asked whenever the profile
-- is chosen in a browser (PBKDF2, with the algorithm's id in front, so a stronger one can follow).
CREATE TABLE users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             TEXT         NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    image_changed_at TIMESTAMPTZ,
    assistant        VARCHAR(20)  NOT NULL DEFAULT 'CLAUDE_CODE' CHECK (assistant IN ('CLAUDE_CODE', 'CODEX')),
    public_id        UUID         NOT NULL DEFAULT gen_random_uuid() CONSTRAINT users_public_id_key UNIQUE,
    password_hash    VARCHAR(255)
);

CREATE UNIQUE INDEX users_name_lower_key ON users (lower(name));

-- A profile's photo: a small square PNG, apart from users so that listing the profiles never reads the images.
CREATE TABLE profile_images (
    user_id BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    image   BYTEA  NOT NULL
);
