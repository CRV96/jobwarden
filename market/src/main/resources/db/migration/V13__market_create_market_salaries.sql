-- What positions pay, per country, from sources that are imported rather than asked live: the Stack Overflow Developer
-- Survey's answers, summed up per country, role and skill (a programming language). An empty country, role or skill
-- is all of them: '' and not NULL, so the unique key covers them.
CREATE TABLE market_salaries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source         VARCHAR(20)    NOT NULL CHECK (source IN ('STACK_OVERFLOW')),
    survey_year    INTEGER        NOT NULL,
    country        VARCHAR(2)     NOT NULL,
    role           TEXT           NOT NULL,
    skill          TEXT           NOT NULL,
    sample_size    INTEGER        NOT NULL CHECK (sample_size > 0),
    lower_quartile NUMERIC(14, 2) NOT NULL,
    median         NUMERIC(14, 2) NOT NULL,
    upper_quartile NUMERIC(14, 2) NOT NULL,
    currency       VARCHAR(3)     NOT NULL,
    imported_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    UNIQUE (source, role, skill, country)
);
